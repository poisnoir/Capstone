#!/usr/bin/env python3
"""Generate docs/reference/MANIFEST.md from manifest.yml.

Usage:
    python3 tools/gen_reference_manifest.py          # write MANIFEST.md
    python3 tools/gen_reference_manifest.py --check  # fail if out of date
"""
from __future__ import annotations

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "docs/reference/manifest.yml"
OUT = ROOT / "docs/reference/MANIFEST.md"


def cell(value: object) -> str:
    if isinstance(value, bool):
        value = "yes" if value else "no"
    text = str(value).replace("|", "\\|").replace("\n", " ")
    return text.strip()


def main() -> int:
    data = yaml.safe_load(SRC.read_text(encoding="utf-8"))
    entries = data.get("entries", [])
    if not entries:
        print(f"{SRC}: no entries", file=sys.stderr)
        return 1

    lines: list[str] = []
    lines.append("# Reference manifest")
    lines.append("")
    lines.append(
        "These files are **not in the repository** (copyright, size, or both). "
        "Each row says what it is, which docs use it, and how to obtain it. "
        "`manifest.yml` is the source of truth; this page is generated by "
        "`python3 tools/gen_reference_manifest.py`."
    )
    lines.append("")
    lines.append(
        "`python3 tools/check_references.py` verifies that every external file "
        "referenced in a doc has a row here. The repo is public; run the "
        "**public-repo checklist** at the bottom before a release."
    )
    lines.append("")
    lines.append(f"Manifest version: {data.get('version', '?')} · updated {data.get('updated', '?')}")
    lines.append("")
    lines.append("| ID | File | Size | Needed for | How to obtain | Publish? |")
    lines.append("|---|---|---|---|---|---|")
    for e in entries:
        obtain = e.get("obtain", {}) or {}
        how = cell(obtain.get("method", ""))
        url = obtain.get("url") or ""
        if url:
            how += f" — {cell(url)}"
        needed = "; ".join(cell(x) for x in e.get("needed_for", []) or [])
        lines.append(
            f"| {cell(e.get('id', ''))} | `{cell(e.get('file', ''))}` | "
            f"{cell(e.get('size', ''))} | {needed} | {how} | "
            f"{cell(e.get('publish', ''))} |"
        )
    lines.append("")
    lines.append("## Acquisition details")
    lines.append("")
    for e in entries:
        obtain = e.get("obtain", {}) or {}
        lines.append(f"### {e.get('id', '?')} — {cell(e.get('title', ''))}")
        lines.append("")
        lines.append(f"- **File:** `{e.get('file', '')}`")
        lines.append(f"- **Size:** {e.get('size', '?')}")
        needed = "; ".join(e.get("needed_for", []) or [])
        lines.append(f"- **Needed for:** {needed}")
        lines.append(f"- **How to obtain:** {obtain.get('method', '?')}")
        if obtain.get("url"):
            lines.append(f"- **URL:** {obtain['url']}")
        if obtain.get("local"):
            lines.append(f"- **Local path:** `{obtain['local']}`")
        lines.append(f"- **Publish:** {e.get('publish', '?')}")
        if e.get("sha256"):
            lines.append(f"- **SHA-256:** `{e['sha256']}`")
        if e.get("regenerate"):
            lines.append(f"- **Regenerate:** {e['regenerate']}")
        lines.append("")

    lines.append("## Regenerating the thesis extracts")
    lines.append("")
    lines.append(
        "The `.txt` extracts and the 27-page PDF crop are local-only (not "
        "tracked). Both are generated from REF-01:"
    )
    lines.append("")
    lines.append("```bash")
    lines.append("# default: ./HAJ_Thesis_2018.pdf; override with THESIS=/path/to/thesis.pdf")
    lines.append("./tools/extract_jaeger.sh")
    lines.append("```")
    lines.append("")
    lines.append("## Public-repo checklist")
    lines.append("")
    lines.append("- [ ] Confirm the Phase 1 report is not tracked: `git ls-files | grep -i 'Phase 1 Report'` is empty.")
    lines.append("- [ ] Confirm the thesis `.txt` extracts are not tracked.")
    lines.append("- [ ] Confirm no tracked PDFs: `git ls-files | grep -i '\\.pdf$'` is empty.")
    lines.append("- [ ] Run `python3 tools/check_publish.py --public`.")
    lines.append("- [ ] Run `python3 tools/check_references.py` and `python3 tools/check_doc_paths.py`.")
    lines.append("- [ ] Flip visibility, then enable the branch ruleset (PR, 1 approval, code owners, status checks).")
    lines.append("")

    text = "\n".join(lines) + "\n"
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT} is out of date; run python3 tools/gen_reference_manifest.py", file=sys.stderr)
            return 1
        print(f"{OUT} is up to date")
        return 0

    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(entries)} entries)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
